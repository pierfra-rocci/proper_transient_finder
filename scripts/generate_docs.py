"""Generate GitHub-readable API Markdown from source without importing dependencies."""

from __future__ import annotations

import argparse
import ast
import copy
from pathlib import Path


def definitions(path: Path) -> dict:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    return {
        node.name: node for node in tree.body if isinstance(node, (ast.ClassDef, ast.FunctionDef))
    }


def signature(node: ast.FunctionDef, name: str, *, method: bool = False) -> str:
    arguments = copy.deepcopy(node.args)
    if method:
        arguments.args = arguments.args[1:]
    result = f"{name}({ast.unparse(arguments)})"
    if node.returns is not None and name != "ProperTransientFinder":
        result += f" -> {ast.unparse(node.returns)}"
    return result


def render_api(project: Path) -> str:
    package = project / "src/proper_transient_finder"
    api = definitions(package / "api.py")
    core = definitions(package / "astro.py")
    survey = definitions(package / "survey.py")
    version_tree = ast.parse((package / "_version.py").read_text(encoding="utf-8"))
    release = next(
        ast.literal_eval(node.value)
        for node in version_tree.body
        if isinstance(node, ast.Assign)
        and any(
            isinstance(target, ast.Name) and target.id == "__version__" for target in node.targets
        )
    )
    lines = [
        "# Python API",
        "",
        "**Author:** Pier-Francesco Rocci",
        "",
        "Developed with assistance from ChatGPT, Claude, and Mistral.",
        "",
        f"Version: `{release}`",
        "",
        (
            "Generated from source by `scripts/docs.ps1` (or `scripts/tasks.sh docs`). "
            "Do not edit this file manually."
        ),
        "",
        "[Quick Start](../README.md) | [User Guide](../USER_GUIDE.md)",
        "",
        "Import public symbols from `proper_transient_finder`. Coordinates are zero-based;",
        "candidate scores do not confirm astrophysical variability.",
        "",
    ]
    for name in (
        "compare_images",
        "compare_batch",
        "load_batch_manifest",
        "prepare_template_request",
        "fetch_survey_template",
        "compare_survey_images",
        "compare_survey_batch",
        "load_science_list",
        "TemplateRequest",
        "SurveyTemplate",
        "BatchJob",
        "BatchItemResult",
        "BatchResult",
        "PipelineConfig",
        "PipelineResult",
        "ProperTransientFinder",
        "compare_cross_filter",
        "main",
    ):
        node = api.get(name) or survey.get(name) or core[name]
        lines += [f"## {name}", ""]
        if isinstance(node, ast.FunctionDef):
            lines += ["```python", signature(node, name), "```", ""]
        description = ast.get_docstring(node)
        if description:
            lines += [description.replace("``", "`"), ""]
        fields = [child for child in node.body if isinstance(child, ast.AnnAssign)]
        if fields:
            lines += ["| Field | Type | Default |", "| --- | --- | --- |"]
            for field in fields:
                annotation = ast.unparse(field.annotation).replace("|", r"\|")
                default = ast.unparse(field.value) if field.value is not None else "required"
                lines.append(f"| `{ast.unparse(field.target)}` | `{annotation}` | `{default}` |")
            lines.append("")
        if name == "ProperTransientFinder":
            methods = {
                child.name: child for child in node.body if isinstance(child, ast.FunctionDef)
            }
            for method_name in (
                "__init__",
                "preflight",
                "perform_image_subtraction",
                "detect_sources_in_difference",
                "run_full_pipeline",
            ):
                method = methods[method_name]
                label = name if method_name == "__init__" else f"{name}.{method_name}"
                lines += ["```python", signature(method, label, method=True), "```", ""]
                description = ast.get_docstring(method)
                if description:
                    lines += [description.replace("``", "`"), ""]
    lines += [
        "## Configuration Validation",
        "",
        "Defaults above are read directly from the dataclass. Range and compatibility",
        "checks are enforced by `PipelineConfig`; see the user guide for their meaning.",
        "",
        "## Acknowledgments",
        "",
        "- [ProperImage](https://github.com/quatrope/ProperImage) "
        "for astronomical image processing.",
        "- [Astropy](https://www.astropy.org/) for FITS, WCS, and astronomy utilities.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    project = Path(__file__).resolve().parents[1]
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=project / "docs/API.md")
    parser.add_argument("--check", action="store_true", help="Fail if generated Markdown is stale")
    args = parser.parse_args(argv)
    content = render_api(project)
    if args.check:
        if not args.output.is_file() or args.output.read_text(encoding="utf-8") != content:
            print(
                f"API documentation is missing or stale: {args.output}. "
                "Run scripts/docs.ps1 or scripts/tasks.sh docs."
            )
            return 1
        print("API documentation is current.")
        return 0
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(content, encoding="utf-8", newline="\n")
    print(f"Generated GitHub Markdown: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
